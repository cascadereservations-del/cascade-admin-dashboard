// Pure part of sync-tokens.mjs (kept apart so a test can import it).
export function derive(src) {
  const body = (sel) => {
    const i = src.indexOf(sel + ' {');
    if (i < 0) throw new Error('tokens.css has no ' + sel + ' block');
    const s = src.indexOf('{', i) + 1;
    return src.slice(s, src.indexOf('\n}', s));
  };
  return `/* GENERATED by scripts/sync-tokens.mjs from the Cascade Staff app tokens.css (v5). Do not edit: change staff-app/tokens.css, then re-run the script.
   Light = the bare :root block, dark = the :root[data-theme="dark"] block re-keyed to .dark (set by use-theme). */
:root {${body(':root')}
}

.dark {${body(':root[data-theme="dark"]')}
}
`;
}

